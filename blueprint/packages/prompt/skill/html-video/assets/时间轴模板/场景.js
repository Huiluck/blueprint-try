const timeline = gsap.timeline({ paused: true })
timeline.fromTo('h1', { opacity: 0, y: 20 }, { opacity: 1, y: 0, duration: 0.7 }, 0)
timeline.fromTo('.source', { opacity: 0, x: -35 }, { opacity: 1, x: 0, duration: 0.8 }, 0.7)
timeline.fromTo('.connector', { opacity: 0, scaleX: 0.2 }, { opacity: 1, scaleX: 1, duration: 0.8 }, 2.2)
timeline.fromTo('.result', { opacity: 0, x: 35 }, { opacity: 1, x: 0, duration: 0.8 }, 3.2)
timeline.set('#caption', { textContent: '让各自的工作在共同目标下汇合。' }, 2.2)
timeline.set('#caption', { textContent: '最后用实际成果判断是否达到目标。' }, 5.4)
timeline.to('.result', { backgroundColor: '#347b60', duration: 0.8 }, 5.4)
timeline.to({}, { duration: 1.8 }, 6.2)
window.__timelines = { explanation: timeline }
const input = document.getElementById('time'), readout = document.getElementById('readout')
timeline.eventCallback('onUpdate', () => { input.value = timeline.time(); readout.textContent = `${timeline.time().toFixed(2)} 秒` })
input.addEventListener('input', () => timeline.pause().seek(Number(input.value), false))
document.getElementById('play').addEventListener('click', () => { if (timeline.time() >= 8) timeline.seek(0); timeline.paused(!timeline.paused()) })
timeline.seek(0, false)
