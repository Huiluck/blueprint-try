// 隐藏窗口连接离线核对宿主，只检查 DOM 与请求，不读取用户项目或截图。
const {app, BrowserWindow} = require('electron')
const assert = require('node:assert/strict')
const {mkdtempSync, writeFileSync, rmSync} = require('node:fs')
const {join} = require('node:path')
const {tmpdir} = require('node:os')
const [origin, token, workerSession, doSession, seq, callId] = process.argv.slice(2)
const profile = mkdtempSync(join(tmpdir(), 'Blueprint 材料浏览界面核对-'))
app.setPath('userData', profile)
const preload = join(profile, '材料预览测试桥.cjs')
writeFileSync(preload, `const {contextBridge}=require('electron'); const {previewURL}=require(${JSON.stringify(join(__dirname, '../runtime/preview.cjs'))}); contextBridge.exposeInMainWorld('blueprintDesktop',{previewURL:(session,path)=>previewURL(${JSON.stringify(origin)},${JSON.stringify(token)},session,path)});`)
let win
const deadline = setTimeout(() => {console.error('材料浏览界面核对超时'); app.exit(1)}, 45000)
app.whenReady().then(async () => {
  app.dock?.hide()
  try {
    win = new BrowserWindow({show:false, width:1200, height:900, webPreferences:{preload, contextIsolation:true, nodeIntegration:false, sandbox:false}})
    win.webContents.setBackgroundThrottling(false)
    win.webContents.on('console-message',event => {if(event.level === 'error') console.error(event.message)})
    await win.webContents.session.cookies.set({url:origin, name:'blueprint_session', value:token, path:'/', httpOnly:true})
    await win.loadURL(`${origin}/studio/?session=${encodeURIComponent(workerSession)}`)
    const run = source => win.webContents.executeJavaScript(`(() => eval(${JSON.stringify(source)}))()`, true).catch(error => {throw new Error(source + '\n' + error.message)})
    const wait = async source => {
      const end = Date.now() + 10000
      while (Date.now() < end) {if(await run(source)) return; await new Promise(done=>setTimeout(done,50))}
      throw new Error('材料界面未达到预期：' + source)
    }
    await wait(`S.sess === ${JSON.stringify(workerSession)} && !!产物画廊`)
    await run(`showTab('artifacts'); const selector=document.querySelector('[aria-label="产物与材料"]'); selector.value='assets'; selector.dispatchEvent(new Event('change')); true`)
    const click = label => run(`document.querySelector(${JSON.stringify(`[aria-label="${label}"]`)}).click(); true`)
    await wait(`!!document.querySelector('[aria-label="打开目录 素材浏览核对"]')`)
    await click('打开目录 素材浏览核对')
    await wait(`!!document.querySelector('[aria-label="打开目录 动作逐帧"]')`)
    assert.equal(await run(`!!document.querySelector('[aria-label="定位文件 模型.glb"]') && !!document.querySelector('[aria-label="打开 角色.gd"]') && !!document.querySelector('[aria-label="打开 动作.mp4"]') && !!document.querySelector('[aria-label="打开 声音.wav"]')`), true, '全部格式保留可用入口')
    assert.equal(await run(`document.querySelectorAll('.material-browser video,.material-browser audio').length`), 0, '列表不提前加载音视频')
    await click('打开目录 动作逐帧')
    await wait(`document.querySelectorAll('.material-browser .artifact-card').length === 60 && document.querySelector('.material-browser .artifact-status').textContent.includes('/ 137')`)
    const first = await run(`document.querySelector('.material-browser .artifact-card').dataset.artifact`)
    await run(`[...document.querySelectorAll('.material-paging button')].find(button=>button.textContent === '下一页').click(); true`)
    await wait(`document.querySelector('.material-browser .artifact-status').textContent.startsWith('61–120')`)
    assert.notEqual(await run(`document.querySelector('.material-browser .artifact-card').dataset.artifact`), first)
    await run(`const selector=document.querySelector('[aria-label="产物与材料"]'); selector.value='process'; selector.dispatchEvent(new Event('change')); true`)
    await wait(`!!document.querySelector('[aria-label="打开目录 .blueprint-tmp"]')`)
    await click('打开目录 .blueprint-tmp')
    await wait(`!!document.querySelector('[aria-label="打开目录 素材浏览候选"]')`)
    await click('打开目录 素材浏览候选')
    await wait(`document.querySelector('.material-browser img')?.naturalWidth > 0`)
    await click('打开 拼图.png')
    await wait(`!!document.querySelector('.leftpage .lp-img')`)
    await run(`左切到('页:预览:.blueprint-tmp/素材浏览候选/拼图.png'); true`)
    await wait(`document.querySelector('.leftpage .lp-img')?.naturalWidth > 0`)
    await run(`切到({在:'project',看:${JSON.stringify(doSession)}}).then(()=>{showTab('trace'); return true;})`)
    await wait(`S.sess === ${JSON.stringify(doSession)} && S.flat.some(cell=>cell.sourceSeq === ${Number(seq)} && cell.callId === ${JSON.stringify(callId)})`)
    await run(`openCell(S.flat.find(cell=>cell.sourceSeq === ${Number(seq)} && cell.callId === ${JSON.stringify(callId)})); true`)
    await wait(`[...document.querySelectorAll('.context-materials .artifact-card')].some(card=>card.dataset.artifact.startsWith('https://example.test/blueprint'))`)
    console.log('材料界面核对通过：目录分组、60 项分页、全部格式入口、按需图片预览与 context 对应记录来源。')
    clearTimeout(deadline); win.destroy(); rmSync(profile,{recursive:true,force:true}); app.exit(0)
  } catch (error) {
    console.error(error.stack); clearTimeout(deadline); win?.destroy(); rmSync(profile,{recursive:true,force:true}); app.exit(1)
  }
})
